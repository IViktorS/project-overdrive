using UnityEngine;

/// <summary>
/// Контракт объекта, способного получать урон: манекен, враг, разрушаемый реквизит.
/// </summary>
/// <remarks>
/// Существует, чтобы боевой код (волна, снаряды врагов) не знал о конкретных классах.
/// До этого <see cref="Wave"/> искал именно <see cref="Dummy"/>, и каждый новый тип
/// цели требовал бы правки боевой логики. По дизайн-документу типов врагов минимум
/// пять, плюс разрушаемый реквизит в комнатах — привязка к классу не масштабируется.
/// </remarks>
public interface IDamageable
{
    /// <summary>
    /// Наносит объекту урон.
    /// </summary>
    /// <param name="damage">Величина урона.</param>
    /// <param name="fromDirection">
    /// Направление, откуда пришёл удар. Нужно для отброса и направленных эффектов попадания.
    /// </param>
    void TakeHit(float damage, Vector2 fromDirection);
}
